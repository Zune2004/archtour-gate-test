import fs from "node:fs";
import path from "node:path";
import { scanRepo } from "./scan.mjs";
import { computeSpecDiff, createVisualDiffSpec, formatMarkdownDiff, mdText, mdCode } from "./diff.mjs";

function isInsideCode(str) {
  let inCode = false;
  let openFenceLen = 0;
  let i = 0;
  while (i < str.length) {
    if (str[i] === "`") {
      let runLen = 0;
      while (i < str.length && str[i] === "`") {
        runLen++;
        i++;
      }
      if (!inCode) {
        inCode = true;
        openFenceLen = runLen;
      } else if (runLen === openFenceLen) {
        inCode = false;
        openFenceLen = 0;
      }
    } else {
      i++;
    }
  }
  return inCode;
}

function isInsideComment(str) {
  const lastOpen = str.lastIndexOf("<!--");
  const lastClose = str.lastIndexOf("-->");
  return lastOpen !== -1 && lastOpen > lastClose;
}

export function truncateMarkdown(md, max = 60000) {
  if (!md || md.length <= max) return md;

  const suffix = "\n\n_Truncated: the full diff is in the workflow artifact._";
  const targetLen = max - suffix.length;
  if (targetLen <= 0) {
    return suffix.trim();
  }

  let cutIndex = md.lastIndexOf("\n", targetLen);
  while (cutIndex > 0) {
    const candidate = md.slice(0, cutIndex);
    if (!isInsideComment(candidate) && !isInsideCode(candidate)) {
      return candidate + suffix;
    }
    cutIndex = md.lastIndexOf("\n", cutIndex - 1);
  }

  const fallbackCut = md.lastIndexOf("\n", targetLen);
  const finalCut = fallbackCut !== -1 ? fallbackCut : targetLen;
  return md.slice(0, finalCut) + suffix;
}

export function formatRepoMarkdownDiff(diffResult, opts = {}) {
  const {
    hasChanges,
    addedSources,
    removedSources,
    modifiedSources,
    newHeadParseErrors = [],
    bothParseFailures = [],
    truncated,
    reason
  } = diffResult;

  const warningHeader = truncated
    ? `⚠️ Partial scan: ${String(reason || "").replace(/\.+$/, "")}. Removed/added sources are not reported; narrow 'paths' or raise --max-files.\n\n`
    : "";

  if (!hasChanges) {
    let out = `${warningHeader}### 📊 Architecture Changes\n\nNo architecture changes`;
    if (bothParseFailures.length > 0) {
      out += "\n\n#### ⚠️ Skipped files\n\n##### Not compared\n";
      for (const f of bothParseFailures) {
        out += `- ${mdCode(f.path)}: could not be parsed (${mdText(f.shortError)})\n`;
      }
    }
    return out.trim();
  }

  const lines = [];
  if (truncated) {
    lines.push(`⚠️ Partial scan: ${String(reason || "").replace(/\.+$/, "")}. Removed/added sources are not reported; narrow 'paths' or raise --max-files.\n`);
  }
  lines.push("### 📊 Architecture Changes\n");
  lines.push("<!-- archtour-diff -->\n");

  lines.push("| Element | Count |");
  lines.push("|---|---|");
  lines.push(`| **Added Sources** | ${addedSources.length} |`);
  lines.push(`| **Removed Sources** | ${removedSources.length} |`);
  lines.push(`| **Modified Sources** | ${modifiedSources.length} |\n`);

  if (addedSources.length > 0) {
    lines.push("#### 🟢 Added Sources");
    for (const s of addedSources) {
      lines.push(`- ${mdCode(s.path)}: added source (${mdText(s.kind)}, ${mdText(s.headItem?.summary || "1 source")})`);
    }
    lines.push("");
  }

  if (removedSources.length > 0) {
    lines.push("#### 🔴 Removed Sources");
    for (const s of removedSources) {
      lines.push(`- ${mdCode(s.path)}: removed source (${mdText(s.kind)}, ${mdText(s.baseItem?.summary || "1 source")})`);
    }
    lines.push("");
  }

  if (modifiedSources.length > 0) {
    lines.push("#### 🟠 Modified Sources\n");
    for (const s of modifiedSources) {
      const srcMd = formatMarkdownDiff(s.diff, {
        title: s.path,
        footer: false,
        isCompose: s.kind === "Services"
      });
      lines.push(srcMd);
      lines.push("");
    }
  }

  const hasSkipped = newHeadParseErrors.length > 0 || bothParseFailures.length > 0;
  if (hasSkipped) {
    lines.push("#### ⚠️ Skipped files\n");
    for (const f of newHeadParseErrors) {
      lines.push(`- ⚠️ ${mdCode(f.path)}: could not be parsed in this PR (${mdText(f.shortError)})`);
    }
    if (bothParseFailures.length > 0) {
      lines.push("\n##### Not compared\n");
      for (const f of bothParseFailures) {
        lines.push(`- ${mdCode(f.path)}: could not be parsed (${mdText(f.shortError)})`);
      }
    }
    lines.push("");
  }

  if (opts.footer !== false) {
    lines.push("*Generated by [Archtour](https://github.com/Zune2004/archtour).*");
  }

  return lines.join("\n").trim();
}

export function createRepoVisualDiffSpec(diffResult, opts = {}) {
  const { addedSources, removedSources, modifiedSources } = diffResult;
  const overviewNodes = [];
  const steps = [];

  for (let i = 0; i < addedSources.length; i++) {
    const s = addedSources[i];
    const id = `added-${i}`;
    overviewNodes.push({
      id,
      label: `+ ${s.kind} · ${s.headItem?.summary || "Added"}\n${s.path}`,
      shape: "rectangle",
      color: "green",
      tooltip: `[Added Source] ${s.path}`,
      detail: `### 🟢 Added Source: ${s.path}\n\n**${s.headItem?.summary || "Added source"}**\n\nClick the drill badge to explore this architecture diagram.`,
      drill: s.visualDiffSpec
    });
    steps.push({
      title: `Added: ${s.path}`,
      text: `Added ${s.kind.toLowerCase()} architecture source with ${s.headItem?.summary || "components"}.`,
      nodes: [id],
      dive: [id]
    });
  }

  for (let i = 0; i < removedSources.length; i++) {
    const s = removedSources[i];
    const id = `removed-${i}`;
    overviewNodes.push({
      id,
      label: `- ${s.kind} · ${s.baseItem?.summary || "Removed"}\n${s.path}`,
      shape: "rectangle",
      color: "red",
      tooltip: `[Removed Source] ${s.path}`,
      detail: `### 🔴 Removed Source: ${s.path}\n\n**${s.baseItem?.summary || "Removed source"}**\n\nClick the drill badge to explore the removed diagram.`,
      drill: s.visualDiffSpec
    });
    steps.push({
      title: `Removed: ${s.path}`,
      text: `Removed ${s.kind.toLowerCase()} architecture source with ${s.baseItem?.summary || "components"}.`,
      nodes: [id],
      dive: [id]
    });
  }

  for (let i = 0; i < modifiedSources.length; i++) {
    const s = modifiedSources[i];
    const id = `modified-${i}`;
    const diffSummary = `${s.diff.addedNodes.length} added, ${s.diff.removedNodes.length} removed, ${s.diff.modifiedNodes.length} modified`;
    overviewNodes.push({
      id,
      label: `~ ${s.kind} · ${diffSummary}\n${s.path}`,
      shape: "rectangle",
      color: "orange",
      tooltip: `[Modified Source] ${s.path}`,
      detail: `### 🟠 Modified Source: ${s.path}\n\nSummary: **${diffSummary}**.\n\nClick the drill badge to explore the visual architecture diff.`,
      drill: s.visualDiffSpec
    });
    steps.push({
      title: `Modified: ${s.path}`,
      text: `Modified ${s.kind.toLowerCase()} architecture in ${s.path}: ${diffSummary}.`,
      nodes: [id],
      dive: [id]
    });
  }

  if (overviewNodes.length === 0) {
    if (diffResult?.newHeadParseErrors && diffResult.newHeadParseErrors.length > 0) {
      overviewNodes.push({
        id: "parse-errors",
        label: "Parse errors in PR",
        color: "red",
        detail: `### ⚠️ Parse Errors\n\nCould not parse ${diffResult.newHeadParseErrors.length} file(s) in this PR.`
      });
      steps.push({
        title: "Parse Errors",
        text: `Encountered parse errors in ${diffResult.newHeadParseErrors.length} file(s).`,
        nodes: ["parse-errors"]
      });
    } else {
      overviewNodes.push({
        id: "no-changes",
        label: "No architecture changes",
        color: "gray",
        detail: "### No architecture changes\n\nNo architectural changes detected between base and head."
      });
      steps.push({
        title: "No Changes",
        text: "No architecture changes detected.",
        nodes: ["no-changes"]
      });
    }
  }

  return {
    title: "Architecture Diff",
    direction: "LR",
    preset: "clean",
    nodes: overviewNodes,
    edges: [],
    steps
  };
}

export function diffRepo(baseDir, headDir, opts = {}) {
  const resolvedBase = path.resolve(baseDir);
  const resolvedHead = path.resolve(headDir);

  if (!fs.existsSync(resolvedBase)) {
    throw new Error(`Base directory does not exist: ${baseDir}`);
  }
  if (!fs.existsSync(resolvedHead)) {
    throw new Error(`Head directory does not exist: ${headDir}`);
  }

  const rawIgnores = opts.ignore
    ? (Array.isArray(opts.ignore) ? opts.ignore : [opts.ignore])
    : [];
  const ignore = rawIgnores.flatMap(x => String(x).split(",")).map(s => s.trim()).filter(Boolean);

  const scanOpts = {
    ignore,
    noSplit: true,
    maxNodes: opts.maxNodes,
    maxFiles: opts.maxFiles,
    maxDepth: opts.maxDepth,
    includeTests: opts.includeTests
  };

  let baseRes = null;
  let baseFound = [];
  let baseParseErrors = [];
  try {
    baseRes = scanRepo(resolvedBase, scanOpts);
    baseFound = baseRes?.found || [];
    baseParseErrors = baseRes?.parseErrors || [];
  } catch (err) {
    if (!err.message.includes("No Prisma schema, Docker Compose file or OpenAPI JSON found")) {
      throw err;
    }
    baseParseErrors = err.parseErrors || [];
  }

  let headRes = null;
  let headFound = [];
  let headParseErrors = [];
  try {
    headRes = scanRepo(resolvedHead, scanOpts);
    headFound = headRes?.found || [];
    headParseErrors = headRes?.parseErrors || [];
  } catch (err) {
    if (!err.message.includes("No Prisma schema, Docker Compose file or OpenAPI JSON found")) {
      throw err;
    }
    headParseErrors = err.parseErrors || [];
  }

  const baseParseMap = new Map(baseParseErrors.map(e => [e.path, e]));
  const headParseMap = new Map(headParseErrors.map(e => [e.path, e]));
  const baseFoundMap = new Map(baseFound.map(item => [item.path, item]));

  const newHeadParseErrors = [];
  const bothParseFailures = [];

  for (const [relPath, errObj] of headParseMap.entries()) {
    const shortError = (errObj.error || "Parse error").split(/\r?\n/)[0].replace(/^Error:\s*/, "").trim();
    if (baseParseMap.has(relPath)) {
      bothParseFailures.push({
        path: relPath,
        error: errObj.error,
        shortError
      });
    } else {
      newHeadParseErrors.push({
        path: relPath,
        error: errObj.error,
        shortError,
        parsedInBase: baseFoundMap.has(relPath)
      });
    }
  }

  const isTruncated = Boolean(baseRes?.truncated || headRes?.truncated);
  let truncationReason = null;
  if (baseRes?.truncated && headRes?.truncated) {
    truncationReason = baseRes.reason || headRes.reason;
  } else if (baseRes?.truncated) {
    truncationReason = baseRes.reason;
  } else if (headRes?.truncated) {
    truncationReason = headRes.reason;
  }

  const baseMap = new Map(baseFound.map(item => [item.path, item]));
  const headMap = new Map(headFound.map(item => [item.path, item]));

  const addedSources = [];
  const removedSources = [];
  const modifiedSources = [];
  const unchangedSources = [];

  if (!isTruncated) {
    for (const [relPath, headItem] of headMap.entries()) {
      if (!baseMap.has(relPath)) {
        const baseSpec = { title: `(Empty)`, nodes: [], edges: [] };
        const diff = computeSpecDiff(baseSpec, headItem.spec);
        const visualDiffSpec = createVisualDiffSpec(baseSpec, headItem.spec, diff);
        addedSources.push({
          path: relPath,
          kind: headItem.kind,
          headItem,
          diff,
          visualDiffSpec
        });
      }
    }

    for (const [relPath, baseItem] of baseMap.entries()) {
      if (!headMap.has(relPath)) {
        if (headParseMap.has(relPath)) {
          continue;
        }
        const headSpec = { title: `(Removed)`, nodes: [], edges: [] };
        const diff = computeSpecDiff(baseItem.spec, headSpec);
        const visualDiffSpec = createVisualDiffSpec(baseItem.spec, headSpec, diff);
        removedSources.push({
          path: relPath,
          kind: baseItem.kind,
          baseItem,
          diff,
          visualDiffSpec
        });
      }
    }
  }

  for (const [relPath, headItem] of headMap.entries()) {
    if (baseMap.has(relPath)) {
      const baseItem = baseMap.get(relPath);
      const diff = computeSpecDiff(baseItem.spec, headItem.spec);
      if (diff.hasChanges) {
        const visualDiffSpec = createVisualDiffSpec(baseItem.spec, headItem.spec, diff);
        modifiedSources.push({
          path: relPath,
          kind: headItem.kind,
          baseItem,
          headItem,
          diff,
          visualDiffSpec
        });
      } else {
        unchangedSources.push({
          path: relPath,
          kind: headItem.kind,
          baseItem,
          headItem,
          diff
        });
      }
    }
  }

  const hasChanges =
    addedSources.length > 0 ||
    removedSources.length > 0 ||
    modifiedSources.length > 0 ||
    newHeadParseErrors.length > 0;

  const diffResult = {
    hasChanges,
    addedSources,
    removedSources,
    modifiedSources,
    unchangedSources,
    baseFound,
    headFound,
    parseErrors: newHeadParseErrors.map(e => ({ path: e.path, error: e.error })),
    newHeadParseErrors,
    bothParseFailures,
    allHeadParseErrors: headParseErrors,
    truncated: isTruncated,
    reason: truncationReason,
    truncationReason
  };

  const summary = {
    hasChanges,
    truncated: isTruncated,
    parseErrors: newHeadParseErrors.map(e => ({
      path: e.path,
      error: e.error,
      ...(e.shortError ? { shortError: e.shortError } : {})
    })),
    counts: {
      added: addedSources.length,
      removed: removedSources.length,
      modified: modifiedSources.length,
      unchanged: unchangedSources.length,
      addedSources: addedSources.length,
      removedSources: removedSources.length,
      modifiedSources: modifiedSources.length,
      unchangedSources: unchangedSources.length,
    }
  };

  const summaryJsonPath = opts.summaryJson || opts["summary-json"];
  if (summaryJsonPath) {
    const summaryDir = path.dirname(path.resolve(summaryJsonPath));
    if (!fs.existsSync(summaryDir)) {
      fs.mkdirSync(summaryDir, { recursive: true });
    }
    fs.writeFileSync(path.resolve(summaryJsonPath), JSON.stringify(summary, null, 2) + "\n");
  }

  const rawMarkdown = formatRepoMarkdownDiff(diffResult, opts);
  const markdown = truncateMarkdown(rawMarkdown, opts.maxMarkdownLength || 60000);
  const overviewSpec = createRepoVisualDiffSpec(diffResult, opts);

  return {
    ...diffResult,
    summary,
    markdown,
    overviewSpec
  };
}
